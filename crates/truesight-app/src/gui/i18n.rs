/// Returns the static UI translation bundle for `lang`.
pub(super) const fn strings(lang: UiLanguage) -> &'static UiStrings {
    match lang {
        UiLanguage::En => &EN,
        UiLanguage::Es => &ES,
        UiLanguage::Ru => &RU,
    }
}

/// Renders compact `[ES] [EN] [RU]` language selector pills and returns the clicked language plus
/// button rectangles in order `[ES, EN, RU]`.
pub(super) fn render_language_selector(
    ui: &mut egui::Ui,
    current: UiLanguage,
) -> (Option<UiLanguage>, [Rect; 3]) {
    let mut selected = None;
    let mut rects = [Rect::NOTHING; 3];
    ui.horizontal(|ui| {
        ui.spacing_mut().item_spacing.x = 2.0;
        for (idx, lang) in UiLanguage::ALL.into_iter().enumerate() {
            let is_on = current == lang;
            let hover = match lang {
                UiLanguage::Es => "Español",
                UiLanguage::En => "English",
                UiLanguage::Ru => "Русский",
            };
            let btn = egui::Button::new(
                RichText::new(lang.code())
                    .size(9.5)
                    .strong()
                    .color(if is_on { P_VOID } else { P_MUTED }),
            )
            .fill(if is_on { P_GEM } else { P_INDIGO_2 })
            .stroke(Stroke::new(1.0_f32, if is_on { P_GEM } else { P_LINE }));
            let resp = ui.add(btn).on_hover_text(hover);
            rects[idx] = resp.rect;
            if resp.clicked() && !is_on {
                selected = Some(lang);
            }
        }
    });
    (selected, rects)
}
