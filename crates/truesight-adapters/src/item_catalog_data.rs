use truesight_core::domain::{ItemCatalogEntry, ItemId};

pub(crate) struct StaticItemRow {
    pub(crate) id: u16,
    pub(crate) slug: &'static str,
    display_name: &'static str,
    pub(crate) cost: u32,
    pub(crate) components: &'static [u16],
    is_recipe: bool,
    is_consumable_drop: bool,
}

impl StaticItemRow {
    pub(crate) fn to_entry(&self) -> ItemCatalogEntry {
        ItemCatalogEntry {
            id: ItemId(self.id),
            slug: self.slug.to_string(),
            display_name: self.display_name.to_string(),
            cost: self.cost,
            components: self.components.iter().copied().map(ItemId).collect(),
            is_recipe: self.is_recipe,
            is_consumable_drop: self.is_consumable_drop,
        }
    }
}

const fn item_row(
    id: u16,
    slug: &'static str,
    display_name: &'static str,
    cost: u32,
    components: &'static [u16],
) -> StaticItemRow {
    StaticItemRow {
        id,
        slug,
        display_name,
        cost,
        components,
        is_recipe: false,
        is_consumable_drop: false,
    }
}

const fn drop_row(
    id: u16,
    slug: &'static str,
    display_name: &'static str,
    components: &'static [u16],
) -> StaticItemRow {
    StaticItemRow {
        id,
        slug,
        display_name,
        cost: 0,
        components,
        is_recipe: false,
        is_consumable_drop: true,
    }
}

